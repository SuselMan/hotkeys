#!/usr/bin/env node
/**
 * Pull packages/protocol/src/*.ts into apps/mobile/src/protocol.ts.
 * Combines the protocol files into one self-contained module so Metro
 * doesn't have to chase ESM-package symlinks across the workspace.
 *
 * Usage:  node scripts/sync-protocol.mjs   (run from apps/mobile)
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const protoSrc = resolve(here, "../../../packages/protocol/src");
const dest = resolve(here, "../src/protocol.ts");

const files = ["keycodes.ts", "service.ts", "messages.ts"];
const parts = await Promise.all(
  files.map((f) => readFile(resolve(protoSrc, f), "utf8")),
);

const stripped = parts
  .join("\n\n")
  .replace(/^import .*?;\s*$/gm, "")
  .replace(/^export \* from .*?;\s*$/gm, "")
  .replace(/from "(\.\/[^"]+)\.js"/g, 'from "$1"')
  .trim();

const banner =
  `/**\n` +
  ` * AUTO-GENERATED by scripts/sync-protocol.mjs.\n` +
  ` * Source of truth: packages/protocol/src/*.ts\n` +
  ` */\n\n`;

await writeFile(dest, banner + stripped + "\n", "utf8");
console.log(`wrote ${dest}`);
